def test_the_scenario_table_has_the_documented_coverage():
    table = scenario_digests()
    assert len(table) == 38 and len(set(table.values())) > 20


def test_every_scenario_result_is_bit_identical_to_the_pre_optimisation_solver():
    assert FROZEN_DIGESTS, "baseline digests must be recorded"
    assert scenario_digests() == FROZEN_DIGESTS


def _true_max_diff(rows, new_rows, cfads, new_cfads, tax, new_tax, d_a, d_b):
    """Independent re-statement of the metric (not a call into the solver)."""
    best = abs(d_a - d_b)
    for ra, rb in zip(rows, new_rows):
        i = ra.period_index
        for x, y in ((ra.opening_keur, rb.opening_keur), (ra.interest_keur, rb.interest_keur),
                     (ra.principal_keur, rb.principal_keur), (ra.closing_keur, rb.closing_keur),
                     (cfads.get(i, 0.0), new_cfads.get(i, 0.0)), (tax.get(i, 0.0), new_tax.get(i, 0.0))):
            best = max(best, abs(x - y))
    return best


@pytest.mark.parametrize("name,case", [
    ("dscr_converged", dict(mode=DSCR, n=14, extra={})),
    ("dscr_max_iter", dict(mode=DSCR, n=14, extra={"overrides": {"maximum_iterations": 3, "damping_alpha": 0.4}})),
    ("gearing_full_tenor_converged", dict(mode=GEARING, n=14, extra={"cost": 120_000.0, "gearing": 0.5, "method": SCULPTED})),
    ("gearing_full_tenor_max_iter", dict(mode=GEARING, n=14, extra={"cost": 120_000.0, "gearing": 0.5, "method": SCULPTED,
                                                                     "overrides": {"maximum_iterations": 2}})),
])
def test_reported_difference_is_the_returning_iterations_true_value_and_computed_once_per_return(monkeypatch, name, case):
    seen = []
    original = solver_mod._compute_max_abs_diff

    def spy(*args):
        value = original(*args)
        seen.append((args, value))
        return value

    monkeypatch.setattr(solver_mod, "_compute_max_abs_diff", spy)
    result, _ = _run(case["n"], case["mode"], _pre_tax(case["n"], 2), **case["extra"])
    reported = result.diagnostics.maximum_absolute_difference_keur
    assert seen, name
    # one computation per RETURNING iteration; the decision never depended on it
    assert len(seen) == 1, (name, len(seen))
    args, value = seen[-1]
    assert reported == value == _true_max_diff(*args)
    assert math.isfinite(reported)


def test_saved_operations_are_the_non_returning_iterations():
    """Baseline computed the metric on every iteration >= 2; the optimised solver computes it once."""
    counted = []
    original = solver_mod._compute_max_abs_diff
    solver_mod._compute_max_abs_diff = lambda *a: (counted.append(1), original(*a))[1]
    try:
        result, _ = _run(14, DSCR, _pre_tax(14, 2), overrides={"maximum_iterations": 50, "damping_alpha": 0.5})
    finally:
        solver_mod._compute_max_abs_diff = original
    iterations = result.diagnostics.iteration_count
    assert iterations >= 3 and len(counted) == 1
    assert iterations - 1 > len(counted)              # the baseline performed iterations - 1 computations


def test_o1_reuse_of_the_dscr_finalisation_is_not_bit_identical_so_it_is_not_implemented():
    """COMBINED_MINIMUM re-runs the finalisation handshake from zero CFADS. When DSCR binds, the sized debt equals the DSCR loop's,
    yet the converged schedule differs in the last digits from the DSCR loop's own finalisation (a different, equally tolerance-valid
    fixed point). Reusing the DSCR result would therefore change financial output; V8-B1 must not do it."""
    pre = _pre_tax(14, 1)
    combined, _ = _run(14, COMBINED, pre, cost=2_000_000.0, gearing=1.0)
    dscr, _ = _run(14, DSCR, pre, cost=2_000_000.0, gearing=1.0)
    assert combined.binding_constraint == "DSCR" and combined.debt_size_keur == dscr.debt_size_keur
    assert combined.senior_interest_keur != dscr.senior_interest_keur
