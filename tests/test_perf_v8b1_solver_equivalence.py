"""Performance V8-B1: the Senior Debt solver optimisation is bit-identical, including every diagnostic value.

O8 computes ``maximum_absolute_difference_keur`` only on the iteration that returns (converged, or the last allowed). The metric
never decides acceptance: ``_schedules_converged`` does. This module proves

* FROZEN_DIGESTS - the complete result of 38 deterministic scenarios (debt size, every schedule float by ``repr``, binding,
  termination reason, iteration count, tolerances reported, maximum absolute/relative difference) equals what the PRE-optimisation
  solver on main produced. The table was generated by running ``scenario_digests()`` unchanged on the baseline tree.
* the reported maximum difference is the true value of the returning iteration, recomputed independently of the solver;
* ``_compute_max_abs_diff`` is called at most once per returning iteration (the saved operations);
* O1 (finalisation reuse) is NOT bit-identical and therefore is not implemented - the characterisation test records why.
"""
from __future__ import annotations

