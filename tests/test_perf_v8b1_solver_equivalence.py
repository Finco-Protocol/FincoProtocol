from financial_engine.senior_debt.solver import solve_senior_debt

DSCR = SeniorDebtSizingMode.DSCR_SCULPTED
COMBINED = SeniorDebtSizingMode.COMBINED_MINIMUM
GEARING = SeniorDebtSizingMode.GEARING_CAP
SCULPTED = GearingCapRepaymentMethod.DSCR_SCULPTED


def _run(n, mode, pre_tax, *, taxable=None, cost=100_000.0, guess=50_000.0, overrides=None, **policy_kw):
    fn = make_tax_fn(pre_tax, taxable=taxable)
    pol = policy(n, mode=mode, **policy_kw)
    if overrides:
        pol = dataclasses.replace(pol, **overrides)
    result = solve_senior_debt(policy=pol, inputs=inputs(cost=cost, guess=guess), periods=periods(n), tax_cfads_fn=fn)
    return result, fn


def _digest(result) -> str:
    d = result.diagnostics
    payload = {
        "debt": repr(result.debt_size_keur), "binding": result.binding_constraint,
        "idx": list(result.period_indices),
        "rows": [[repr(x) for x in getattr(result, name)] for name in (
            "senior_debt_opening_keur", "senior_interest_keur", "senior_principal_keur", "senior_debt_service_keur",
            "senior_debt_closing_keur")],
        "dscr": [None if x is None else repr(x) for x in result.senior_dscr],
        "diag": [d.converged, d.iteration_count, repr(d.initial_debt_guess_keur), repr(d.final_debt_size_keur),
                 repr(d.maximum_absolute_difference_keur), repr(d.maximum_relative_difference), d.binding_constraint,
                 d.termination_reason, d.is_authoritative,
                 None if d.dscr_debt_capacity_keur is None else repr(d.dscr_debt_capacity_keur),
                 None if d.gearing_debt_capacity_keur is None else repr(d.gearing_debt_capacity_keur)],
    }
    return hashlib.sha256(json.dumps(payload, sort_keys=True).encode()).hexdigest()


def _pre_tax(n, seed):
    return {i: 4500.0 + 37.0 * ((i * 7 + seed * 13) % 23) for i in range(1, n + 1)}


def scenario_digests() -> dict[str, str]:
    """Deterministic scenario table. Its digests were produced on the pre-optimisation solver."""
    out: dict[str, str] = {}
    for seed in range(5):                                                       # DSCR-binding (cap far above capacity)
        r, _ = _run(12 + seed, COMBINED, _pre_tax(12 + seed, seed), cost=2_000_000.0, gearing=1.0)
        out[f"dscr_binding_{seed}"] = _digest(r)
    for seed in range(5):                                                       # gearing-binding
        r, _ = _run(12 + seed, COMBINED, _pre_tax(12 + seed, seed), cost=120_000.0, gearing=0.3)
        out[f"gearing_binding_{seed}"] = _digest(r)
    base, _ = _run(14, COMBINED, _pre_tax(14, 1), cost=2_000_000.0, gearing=1.0)
    capacity = base.debt_size_keur
    for delta in (0.0, 5e-5, -5e-5, 2e-4, -2e-4, 1e-3):                       # equal and near-equal binding constraints
        r, _ = _run(14, COMBINED, _pre_tax(14, 1), cost=2_000_000.0, gearing=(capacity + delta) / 2_000_000.0)
        out[f"near_equal_binding_{delta:+.0e}"] = _digest(r)
    for seed in range(3):                                                       # GEARING_CAP with full-tenor DSCR sculpting
        r, _ = _run(14, GEARING, _pre_tax(14, seed), cost=120_000.0, gearing=0.5, method=SCULPTED)
        out[f"gearing_full_tenor_{seed}"] = _digest(r)
    r, _ = _run(10, COMBINED, flat(10, 0.0))                                    # zero capacity
    out["zero_capacity_combined"] = _digest(r)
    r, _ = _run(10, DSCR, flat(10, 0.0))
    out["zero_capacity_dscr"] = _digest(r)
    r, _ = _run(12, DSCR, flat(12, 900.0), balloon=False, maturity=6)           # infeasible / terminal balance prohibited
    out["infeasible_no_balloon"] = _digest(r)
    r, _ = _run(12, COMBINED, flat(12, 600.0), balloon=False, maturity=6, cost=500_000.0, gearing=0.9)
    out["infeasible_combined"] = _digest(r)
    for max_iter in (1, 2, 3, 5):                                               # max-iteration paths (damped so it does not converge)
        r, _ = _run(14, DSCR, _pre_tax(14, 2), overrides={"maximum_iterations": max_iter, "damping_alpha": 0.4})
        out[f"max_iter_dscr_{max_iter}"] = _digest(r)
    for max_iter in (1, 2, 3):
        r, _ = _run(14, GEARING, _pre_tax(14, 2), cost=120_000.0, gearing=0.5, method=SCULPTED,
                    overrides={"maximum_iterations": max_iter})
        out[f"max_iter_gearing_full_tenor_{max_iter}"] = _digest(r)
    for tol in (1e-2, 1e-4, 1e-6, 1e-8):                                        # tolerance-boundary perturbations
        for rel in (0.0, 1e-9):
            r, _ = _run(14, COMBINED, _pre_tax(14, 3), cost=2_000_000.0, gearing=1.0,
                        overrides={"convergence_tolerance_keur": tol, "convergence_relative_tolerance": rel})
            out[f"tolerance_{tol:.0e}_{rel:.0e}"] = _digest(r)
    return out


