"""Canonical-source binding and code authentication for the admitted region (V10-02, V10-03, V10-09).

The kernel may serve a call only if every canonical Python function that the call would execute is
the approved code - not merely the object captured at import:

1. Each region module's source file must match the approved git blob SHA1 (``approved_canonical_
   blobs.json``; in production this is the Financial-Owner protected blob manifest).
2. Each region function's live code object must be structurally identical (bytecode, constants,
   names, nested code - ``code_fingerprint``) to the code object
   compiled from that approved source. Nested functions/closures are covered transitively because a
   parent's code object contains its nested code objects.
3. Region classes must be the module's own class objects; region modules must not shadow builtins;
   the builtins used inside the region must still be the interpreter's builtin objects.

Authentication runs once per process (lazily, only when a Run asks for the candidate). Afterwards a
cheap identity re-check runs before every admission so that any later replacement (monkey patch,
fault injection, wrapper) declines the kernel and the canonical code runs instead.
The REGION list was generated by tracing canonical execution (harness/region_trace.py).
"""
