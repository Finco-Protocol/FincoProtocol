def git_blob_sha1(data: bytes) -> str:
    return hashlib.sha1(b"blob %d\0" % len(data) + data).hexdigest()


def _module_relpath(module) -> str:
    path = Path(module.__file__).resolve()
    root = Path(sys.modules["financial_engine"].__file__).resolve().parent.parent
    return path.relative_to(root).as_posix()


def _resolve(module, qualname: str):
    obj = module
    for part in qualname.split("."):
        obj = obj.__dict__[part] if isinstance(obj, (types.ModuleType, type)) else getattr(obj, part)
    return obj


def _find_code(code: types.CodeType, qualname: str):
    if code.co_qualname == qualname:
        return code
    for const in code.co_consts:
        if isinstance(const, types.CodeType):
            found = _find_code(const, qualname)
            if found is not None:
                return found
    return None


_CODE_ATTRS = ("co_argcount", "co_posonlyargcount", "co_kwonlyargcount", "co_nlocals", "co_stacksize",
               "co_flags", "co_code", "co_names", "co_varnames", "co_freevars", "co_cellvars", "co_name",
               "co_qualname", "co_firstlineno", "co_linetable", "co_exceptiontable")


def code_fingerprint(code: types.CodeType):
    """Structural identity of a code object, recursive over nested code (marshal bytes are not
    stable across equal objects because of reference flags)."""
    consts = tuple(code_fingerprint(c) if isinstance(c, types.CodeType) else (type(c).__name__, repr(c))
                   for c in code.co_consts)
    return tuple(getattr(code, a) for a in _CODE_ATTRS) + (consts,)


def build_manifest(functions=None, extra_sources=None) -> dict:
    """Research helper: record the blobs of the current tree as the approved set."""
    functions = REGION_FUNCTIONS if functions is None else functions
    extra_sources = EXTRA_SOURCES if extra_sources is None else extra_sources
    mods = {}
    for name in functions:
        module = importlib.import_module(name)
        mods[_module_relpath(module)] = git_blob_sha1(Path(module.__file__).read_bytes())
    root = Path(sys.modules["financial_engine"].__file__).resolve().parent.parent
    for rel in extra_sources:
        mods[rel] = git_blob_sha1((root / rel).read_bytes())
    return {"schema": "finco.native_v10.approved_blobs.v1", "blobs": dict(sorted(mods.items())),
            "python_optimize": sys.flags.optimize}


class Authentication:
    """Immutable result of one successful authentication: the exact objects that were verified."""

    __slots__ = ("objects", "builtins_snapshot", "module_dicts", "extra")

    def __init__(self, objects, builtins_snapshot, module_dicts, extra=None):
        self.objects = objects                  # tuple[(owner, name, obj)]
        self.builtins_snapshot = builtins_snapshot
        self.module_dicts = module_dicts
        self.extra = extra                      # optional further Authentication (Stage 2 = Stage 1 + SHL)

    def still_intact(self) -> bool:
        for owner, name, obj in self.objects:
            if owner.__dict__.get(name) is not obj:
                return False
        for name, obj in self.builtins_snapshot:
            if builtins.__dict__.get(name) is not obj:
                return False
        for mdict in self.module_dicts:
            for name in REGION_BUILTINS:
                if name in mdict:
                    return False
        return True if self.extra is None else self.extra.still_intact()


def authenticate(manifest_path: Path = APPROVED_MANIFEST, *, functions=None, attributes=None, aliases=None,
                 extra_sources=None) -> tuple[Authentication | None, str | None]:
    functions = REGION_FUNCTIONS if functions is None else functions
    attributes = REGION_ATTRIBUTES if attributes is None else attributes
    aliases = ALIASES if aliases is None else aliases
    extra_sources = EXTRA_SOURCES if extra_sources is None else extra_sources
    try:
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        return None, f"PROVENANCE_MANIFEST_UNAVAILABLE:{type(exc).__name__}"
    if manifest.get("schema") != "finco.native_v10.approved_blobs.v1":
        return None, "PROVENANCE_MANIFEST_SCHEMA"
    if manifest.get("python_optimize") != sys.flags.optimize:
        return None, "PROVENANCE_PYTHON_OPTIMIZE_FLAG"
    blobs = manifest.get("blobs", {})
    objects = []
    module_dicts = []
    for name, qualnames in functions.items():
        module = sys.modules.get(name) or importlib.import_module(name)
        rel = _module_relpath(module)
        source = Path(module.__file__).read_bytes()
        if blobs.get(rel) != git_blob_sha1(source):
            return None, f"PROVENANCE_BLOB_MISMATCH:{rel}"
        compiled = compile(source, module.__file__, "exec", dont_inherit=True, optimize=sys.flags.optimize)
        module_dicts.append(module.__dict__)
        for qualname in qualnames:
            try:
                live = _resolve(module, qualname)
            except (KeyError, AttributeError):
                return None, f"PROVENANCE_MISSING:{name}.{qualname}"
            func = live
            if not isinstance(func, types.FunctionType):
                return None, f"PROVENANCE_NOT_A_FUNCTION:{name}.{qualname}"
            approved = _find_code(compiled, qualname)
            if approved is None or code_fingerprint(func.__code__) != code_fingerprint(approved):
                return None, f"PROVENANCE_CODE_MISMATCH:{name}.{qualname}"
            if func.__globals__ is not module.__dict__:
                return None, f"PROVENANCE_GLOBALS:{name}.{qualname}"
            owner_name, _, attr = qualname.rpartition(".")
            owner = _resolve(module, owner_name) if owner_name else module
            objects.append((owner, attr, func))
        for attr in attributes.get(name, ()):
            obj = module.__dict__.get(attr)
            if obj is None:
                return None, f"PROVENANCE_MISSING_ATTRIBUTE:{name}.{attr}"
            if isinstance(obj, type):
                home = sys.modules.get(obj.__module__)
                if home is None or not home.__name__.startswith("financial_engine.") or \
                        home.__dict__.get(obj.__name__) is not obj:
                    return None, f"PROVENANCE_CLASS:{name}.{attr}"
            wrapped = getattr(obj, "__wrapped__", None)
            if isinstance(wrapped, types.FunctionType):      # e.g. lru_cache(_period_geometry)
                home = sys.modules.get(wrapped.__module__)
                if home is None or home.__name__ not in functions:
                    return None, f"PROVENANCE_WRAPPED_HOME:{name}.{attr}"
                home_src = Path(home.__file__).read_bytes()
                if blobs.get(_module_relpath(home)) != git_blob_sha1(home_src):
                    return None, f"PROVENANCE_BLOB_MISMATCH:{_module_relpath(home)}"
                home_code = compile(home_src, home.__file__, "exec", dont_inherit=True, optimize=sys.flags.optimize)
                approved = _find_code(home_code, wrapped.__qualname__)
                if approved is None or code_fingerprint(wrapped.__code__) != code_fingerprint(approved):
                    return None, f"PROVENANCE_CODE_MISMATCH:{name}.{attr}"
            objects.append((module, attr, obj))
        for b in REGION_BUILTINS:
            if b in module.__dict__:
                return None, f"PROVENANCE_BUILTIN_SHADOWED:{name}.{b}"
    for src_mod, src_attr, dst_mod, dst_attr in aliases:
        if sys.modules[src_mod].__dict__.get(src_attr) is not _resolve(sys.modules[dst_mod], dst_attr):
            return None, f"PROVENANCE_ALIAS:{src_mod}.{src_attr}"
    root = Path(sys.modules["financial_engine"].__file__).resolve().parent.parent
    for rel in extra_sources:
        if blobs.get(rel) != git_blob_sha1((root / rel).read_bytes()):
            return None, f"PROVENANCE_BLOB_MISMATCH:{rel}"
    snapshot = []
    for b in REGION_BUILTINS:
        obj = builtins.__dict__.get(b)
        ok = isinstance(obj, types.BuiltinFunctionType) and obj.__name__ == b and obj.__self__ is builtins
        ok = ok or (isinstance(obj, type) and obj.__module__ == "builtins" and obj.__name__ == b)
        if not ok:
            return None, f"PROVENANCE_BUILTIN_REPLACED:{b}"
        snapshot.append((b, obj))
    return Authentication(tuple(objects), tuple(snapshot), tuple(module_dicts)), None


def authenticate_stage2(stage1: Authentication) -> tuple[Authentication | None, str | None]:
    auth, reason = authenticate(STAGE2_APPROVED_MANIFEST, functions=STAGE2_REGION_FUNCTIONS,
                                attributes=STAGE2_REGION_ATTRIBUTES, aliases=STAGE2_ALIASES,
                                extra_sources=STAGE2_EXTRA_SOURCES)
    if auth is None:
        return None, f"STAGE2_{reason}"
    return Authentication(stage1.objects, stage1.builtins_snapshot, stage1.module_dicts, extra=auth), None
